from typing import Protocol

class ReplayStore(Protocol):
    async def create_job(self, snapshot_id: str, rate: int, key: str) -> dict: ...
    async def get_job(self, job_id: str) -> dict | None: ...
    async def list_jobs(self, page: int, page_size: int) -> dict: ...
    async def change_job(self, job_id: str, action: str, rate: int | None = None) -> dict: ...
    async def cancel_job(self, job_id: str) -> dict: ...
    async def snapshots(self) -> list[dict]: ...
